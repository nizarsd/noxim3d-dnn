"""Offline analysis of the c16 matrix campaign -> ANALYSIS.txt.

Merges: int6/res_c16knee.txt (minCC arm), res_matrix.txt, res_matrix_patch.txt
(patch rows SUPERSEDE same-tag rows), res_af_n95.txt (aboveF coverage arm).
In-band filter: run_spec/run_spec_patch flags (patched tags take their patched
rung; OOB2 excluded from pooled numbers but listed).
Row format everywhere: tag_kXXXX pol seed mean p99.
"""
import collections, csv, os, statistics as st

K = '/home/nizar/noxim3d-dnn/results_ext/topn/matrix'
I6 = '/home/nizar/noxim3d-dnn/results_ext/topn/int6'
OUTF = open(f'{K}/ANALYSIS.txt', 'w')


def P(s=''):
    print(s, file=OUTF)


def load(fn, into, keep=None):
    if not os.path.exists(fn):
        return
    for ln in open(fn):
        p = ln.split()
        if len(p) < 5 or p[3] == 'NA':
            continue
        tag = p[0].rsplit('_k', 1)[0]
        if keep is not None and tag not in keep:
            continue
        into[(tag, p[1])][int(p[2])] = (float(p[3]), float(p[4]))


# --- specs / band flags ---
spec = {}
for fn in (f'{K}/run_spec.txt', f'{K}/run_spec_patch.txt'):
    if os.path.exists(fn):
        for ln in open(fn):
            t, k, dep, flag = ln.split()
            spec[t] = (k, float(dep), flag)          # patch overwrites
for fn in (f'{I6}/run_spec_c16.txt',):
    if os.path.exists(fn):
        for ln in open(fn):
            t, k, dep = ln.split()[:3]
            spec[t] = (k, float(dep), 'OK' if 4.0 <= float(dep) <= 6.0 else 'OOB')

patched = set()
if os.path.exists(f'{K}/run_spec_patch.txt'):
    patched = {ln.split()[0] for ln in open(f'{K}/run_spec_patch.txt')}

runs = collections.defaultdict(dict)
# main rows, skipping tags that were patched (their rung was replaced)
tmp = collections.defaultdict(dict)
load(f'{K}/res_matrix.txt', tmp)
for (t, pol), d in tmp.items():
    if t not in patched:
        runs[(t, pol)] = d
load(f'{K}/res_matrix_patch.txt', runs)
load(f'{I6}/res_c16knee.txt', runs)

n95 = collections.defaultdict(dict)
load(f'{K}/res_af_n95.txt', n95)


def arm_of(t):
    body = t.split('_', 1)[1]
    for c, a in (('ne40', 'minE40'), ('ne50', 'minE50'), ('e50', 'maxE50'),
                 ('e40', 'maxE40'), ('es', 'maxES'), ('af', 'aboveF'),
                 ('int', 'minCC')):
        if body.startswith(c):
            return a
    return '?'


tags = sorted({t for t, _ in runs})
ARMS = ['minCC', 'maxES', 'maxE50', 'maxE40', 'minE40', 'minE50', 'aboveF']
PACKS = ['r1628', 'v1644', 'esxd']

P('==================================================================')
P('c16 COHERENT MATRIX — ANALYSIS (auto-generated by analyze_matrix.py)')
P('Ratios: BL/DP and BL/HYB mean-delay ratios (>1 = policy beats BL);')
P('DP/HYB >1 = hybrid faster than DP. Paired seeds, in-band cells only.')
P('==================================================================')

percell = {}
for t in tags:
    if t not in spec:
        continue
    k, dep, flag = spec[t]
    bl = runs.get((t, 'bl'), {}); dp = runs.get((t, 'dp'), {})
    hy = runs.get((t, 'hyb'), {})
    c = set(bl) & set(dp)
    if len(c) < 4:
        continue
    row = dict(pack=t.split('_')[0], arm=arm_of(t), dep=dep, flag=flag,
               bl=st.mean(bl[s][0] for s in c),
               blp=st.mean(bl[s][1] for s in c),
               gdm=st.mean(bl[s][0] for s in c) / st.mean(dp[s][0] for s in c),
               gdp=st.mean(bl[s][1] for s in c) / st.mean(dp[s][1] for s in c))
    ch = set(dp) & set(hy)
    if len(ch) >= 4:
        row['dph'] = st.mean(dp[s][0] for s in ch) / st.mean(hy[s][0] for s in ch)
        row['gh'] = st.mean(bl[s][0] for s in ch) / st.mean(hy[s][0] for s in ch)
    percell[t] = row

for pack in PACKS:
    P(f'\n=== {pack} ===')
    P(f"{'arm':8s} {'n':>2s} {'dep':>4s}  {'BL/DP':>6s} [min..max]      "
      f"{'p99':>6s}  {'BL/HYB':>6s}  {'DP/HYB':>6s}  wins(DP>BL)")
    for arm in ARMS:
        cells = [r for t, r in percell.items()
                 if r['pack'] == pack and r['arm'] == arm and r['flag'] == 'OK']
        if not cells:
            continue
        g = [r['gdm'] for r in cells]; gp = [r['gdp'] for r in cells]
        hs = [r['dph'] for r in cells if 'dph' in r]
        gh = [r['gh'] for r in cells if 'gh' in r]
        P(f"{arm:8s} {len(cells):2d} {st.mean(r['dep'] for r in cells):4.1f}  "
          f"{st.mean(g):6.3f} [{min(g):.3f}..{max(g):.3f}]  {st.mean(gp):6.3f}  "
          f"{(st.mean(gh) if gh else float('nan')):6.3f}  "
          f"{(st.mean(hs) if hs else float('nan')):6.3f}  "
          f"{sum(1 for x in g if x > 1.0)}/{len(g)}")
    oob = [t for t, r in percell.items() if r['pack'] == pack and r['flag'] != 'OK']
    if oob:
        P(f"  excluded (out of band): {', '.join(sorted(oob))}")

# --- E-race: arm metric levels vs measured DP gain ---
P('\n=== E-RACE: achieved metric (arm mean) vs BL/DP gain ===')
mets = collections.defaultdict(dict)
for pack in PACKS:
    for fn in (f'{K}/arms_{pack}.csv', f'{K}/arms2_{pack}.csv'):
        if not os.path.exists(fn):
            continue
        for r in csv.DictReader(open(fn)):
            mets[(pack, r['arm'])].setdefault('ES', []).append(float(r['ES']))
            mets[(pack, r['arm'])].setdefault('E50', []).append(float(r['E50']))
            mets[(pack, r['arm'])].setdefault('E40', []).append(float(r['E40']))
for pack in PACKS:
    P(f'  {pack}:')
    for arm in ARMS:
        if arm == 'aboveF':
            continue
        cells = [r for t, r in percell.items()
                 if r['pack'] == pack and r['arm'] == arm and r['flag'] == 'OK']
        m = mets.get((pack, arm), {})
        if not cells or not m:
            continue
        P(f"    {arm:8s} ES {st.mean(m['ES']):+.3f} E50 {st.mean(m['E50']):.3f} "
          f"E40 {st.mean(m['E40']):.3f}  ->  BL/DP {st.mean(r['gdm'] for r in cells):.3f}")

# --- ResNet dissociation readout ---
P('\n=== P4/P3 DECISIVE CELLS (ResNet dissociation) ===')
for arm in ('maxES', 'maxE50', 'maxE40', 'minE40', 'minE50', 'minCC'):
    cells = [r for t, r in percell.items()
             if r['pack'] == 'r1628' and r['arm'] == arm and r['flag'] == 'OK']
    if cells:
        P(f"  {arm:8s} BL/DP {st.mean(r['gdm'] for r in cells):.3f}  "
          f"(n={len(cells)}, BL delay {st.mean(r['bl'] for r in cells):.0f})")

# --- aboveF coverage arm ---
if n95:
    P('\n=== aboveF COVERAGE (hybrid N@95 vs N@90 vs DP) ===')
    for t in sorted({t for t, _ in n95}):
        base = percell.get(t)
        h95 = n95.get((t, 'hyb95'), {}) or n95.get((t, 'hyb'), {})
        dp = runs.get((t, 'dp'), {})
        c = set(h95) & set(dp)
        if base and c:
            r95 = st.mean(dp[s][0] for s in c) / st.mean(h95[s][0] for s in c)
            P(f"  {t:12s} DP/HYB90 {base.get('dph', float('nan')):.3f}   "
              f"DP/HYB95 {r95:.3f}")

# --- prediction scoring ---
P('\n=== REGISTERED-PREDICTION SCORING (heuristic; confirm by eye) ===')
def pool(arm, pack=None):
    cells = [r for t, r in percell.items() if r['arm'] == arm
             and r['flag'] == 'OK' and (pack is None or r['pack'] == pack)]
    return (st.mean(r['gdm'] for r in cells) if cells else float('nan')), len(cells)

g, n = pool('minCC')
P(f"P1 minCC parity |gain-1|<=6%: pooled {g:.3f} (n={n}) -> "
  f"{'PASS' if abs(g-1) <= 0.06 else 'FAIL'}")
g, n = pool('maxES')
hy = [r['dph'] for t, r in percell.items()
      if r['arm'] == 'maxES' and r['flag'] == 'OK' and 'dph' in r]
P(f"P2 maxES DP>=BL: pooled {g:.3f} (n={n}) -> {'PASS' if g >= 1.0 else 'FAIL'}"
  f"; DPN within 6% of DP: {st.mean(hy):.3f}"
  f" -> {'PASS' if hy and abs(st.mean(hy)-1) <= 0.06 else 'FAIL'}" if hy else '')
for pk in PACKS:
    gm40, _ = pool('minE40', pk); gcc, _ = pool('minCC', pk)
    P(f"P4 {pk}: minE40 {gm40:.3f} vs minCC {gcc:.3f} -> "
      f"{'DIRECTION OK' if gm40 > gcc else 'NOT MANUFACTURED'}")
g, n = pool('aboveF')
hy = [r['dph'] for t, r in percell.items()
      if r['arm'] == 'aboveF' and r['flag'] == 'OK' and 'dph' in r]
P(f"P5 aboveF DP>BL: pooled {g:.3f} (n={n}) -> {'PASS' if g > 1.0 else 'FAIL'}"
  + (f"; DPN/DP {st.mean(hy):.3f}" if hy else ''))
P('\nDone.')
OUTF.close()
print('wrote ANALYSIS.txt')
